"""First-run detection: writes a config.yaml that fits this Proxmox host.

    python3 -m pvehomelab.setup                 # print the proposed config
    python3 -m pvehomelab.setup --write PATH    # write it (refuses to overwrite)
    python3 -m pvehomelab.setup --city Lviv --lang en

It finds GPUs that drive a connected monitor (each becomes a seat with its own menu),
monitors reachable over DDC and their input codes, and a container running Caddy.
"""

import argparse
import asyncio
import json
import os
import re
import socket
import sys

from . import gpus as G
from .util import run


async def detect_seats():
    seats = []
    for g in await G.list_gpus(set()):
        if g["driver"] in (None, "vfio-pci"):
            continue
        if not any(c["connected"] for c in g["connectors"]):
            continue
        seats.append(g)
    return seats


async def detect_monitors():
    """[{bus, connector, pci, model, inputs: {code: label}}] from ddcutil."""
    try:
        await run("modprobe", "i2c-dev", check=False)
        out = await run("ddcutil", "detect", "--brief", timeout=60)
    except Exception:
        return []
    mons = []
    for block in out.split("\n\n"):
        bus = re.search(r"/dev/i2c-(\d+)", block)
        conn = re.search(r"DRM connector:\s*(card\d+)-(\S+)", block)
        model = re.search(r"Monitor:\s*(.+)", block)
        if not bus or "Invalid display" in block:
            continue
        pci = None
        if conn:
            dev = os.path.realpath(f"/sys/class/drm/{conn.group(1)}/device")
            pci = os.path.basename(dev)
        inputs = {}
        try:
            caps = await run("ddcutil", "-b", bus.group(1), "capabilities", timeout=40)
            inputs = parse_inputs(caps)
        except Exception:
            pass
        mons.append({"bus": int(bus.group(1)), "connector": conn.group(2) if conn else None, "pci": pci,
                     "model": model.group(1).strip() if model else "?", "inputs": inputs})
    return mons


def parse_inputs(caps):
    """{code: label} of the input source feature (VCP 0x60) in `ddcutil capabilities` output."""
    sect = re.search(r"Feature: 60.*?Values:\n(.*?)(?:\n\s*Feature:|\Z)", caps, re.S)
    return {int(code, 16): label.strip()
            for code, label in re.findall(r"^\s*([0-9a-fA-F]{2}):\s*(.+)$", sect.group(1) if sect else "", re.M)}


def guess_input(connector, inputs):
    """HDMI-A-1 -> 'HDMI-1', DP-2 -> 'DisplayPort-2' among the monitor's advertised inputs."""
    if not connector:
        return None
    m = re.match(r"(HDMI-A|DP|DVI-D|DVI-I|VGA)-(\d+)", connector)
    if not m:
        return None
    kind = {"HDMI-A": "HDMI", "DP": "DisplayPort", "DVI-D": "DVI", "DVI-I": "DVI", "VGA": "VGA"}[m.group(1)]
    for code, label in inputs.items():
        if label.lower().startswith(kind.lower()) and label.endswith(m.group(2)):
            return code
    return None


async def detect_caddy():
    try:
        out = await run("pct", "list", timeout=20)
    except Exception:
        return None
    for line in out.splitlines()[1:]:
        parts = line.split()
        if parts and "caddy" in parts[-1].lower() and "running" in line:
            return int(parts[0])
    return None


def guess_city():
    try:
        tz = os.path.realpath("/etc/localtime").split("zoneinfo/")[-1]
    except OSError:
        tz = ""
    return tz.split("/")[-1].replace("_", " ") if "/" in tz else "Kyiv"


def render(seats, monitors, caddy_ct, city, lang):
    L = []
    w = L.append
    w("# PVE Homelab: generated by `python3 -m pvehomelab.setup` for this host.")
    w("# After editing: systemctl restart pve-homelab 'pve-homelab-kiosk@*'")
    w("")
    w("listen: 127.0.0.1:8900")
    w(f"node: {socket.gethostname().split('.')[0]}")
    w(f"language: {lang}                  # default UI language (uk, en); every user can pick their own")
    w("systems_tag: seat             # VMs with this tag appear under Systems")
    w("systems_extra: []             # untagged VMs to show as well (e.g. hibernated ones can't be tagged)")
    w("")
    w("# A seat = a GPU with a monitor where the host draws its own menu (separate login per seat).")
    w("seats:")
    if not seats:
        w("  {}   # no host-driven GPU with a connected monitor was found")
    for i, g in enumerate(seats):
        sid = "igpu" if g["integrated"] else f"gpu{i}"
        conns = ", ".join(c["name"] for c in g["connectors"] if c["connected"])
        w(f"  {sid}:")
        w(f"    title: {g['name']}   # {conns}")
        w(f"    gpu: \"{g['pci']}\"")
        w(f"    tty: {7 + i}")
        w("    kiosk: true")
    w("")
    w("# Monitors wired to several GPUs: the monitor input for each GPU (DDC/CI, VCP 0x60).")
    w("# Without this section the menu simply won't switch the monitor input by itself.")
    w("monitors:")
    written = False
    seat_pcis = {g["pci"] for g in seats}
    for n, m in enumerate(monitors):
        code = guess_input(m["connector"], m["inputs"])
        if not m["inputs"]:
            continue
        written = True
        w(f"  mon{n}:   # {m['model']}")
        w(f"    ddc_bus: {m['bus']}")
        w("    inputs:")
        if m["pci"] in seat_pcis and code is not None:
            w(f"      \"{m['pci']}\": 0x{code:02x}   # {m['inputs'][code]} (menu)")
        w("      # Add other GPUs wired to this monitor, e.g. the discrete one used by VMs:")
        for c, label in sorted(m["inputs"].items()):
            if c != code:
                w(f"      # \"0000:XX:00.0\": 0x{c:02x}   # {label}")
    if not written:
        w("  {}")
    w("")
    w("launch:")
    w("  assign_gpu: true            # write the chosen GPU into the VM config before start")
    w("  allow_igpu: false           # true = pass the seat GPU through entirely (otherwise VirGL inside the menu)")
    w("  return_to_menu: true        # switch the monitor back to the menu when the VM stops")
    w("")
    w("caddy:")
    w(f"  ct: {caddy_ct if caddy_ct else 'null'}   # container running Caddy; null = no automatic web services")
    w("  admin: http://localhost:2019")
    w("  prefer_suffix: \"\"          # for duplicates (x.example.com / x.internal) keep this suffix")
    w("  hide: []")
    w("")
    w("# Web UIs found without Caddy: open ports of containers/VMs (checked with GET /) and links in guest Notes")
    w("discovery:")
    w("  ports: true")
    w("  vms: true")
    w("  notes: true")
    w("  ignore: []                  # e.g. [ct206, \"ct206:3003\", vm102]")
    w("")
    w("# Nice names and logos (key = first part of the domain, or ct<id>-<port>; icon from github.com/homarr-labs/dashboard-icons)")
    w("services: {}")
    w("#  photos: {name: Photos, icon: immich}")
    w("")
    w("# Links without Caddy (or in addition to it)")
    w("links: []")
    w("#  - {name: Router, url: \"http://192.168.1.1\", icon: openwrt}")
    w("")
    w("weather:")
    w(f"  city: {city}")
    w("  units: c                    # c or f")
    w("")
    w("users:")
    w("  hide: []                    # accounts to hide on the login screen, e.g. [root@pam]")
    w("")
    w("saver:")
    w("  after_min: 5")
    w("lock_after_min: 15")
    w("")
    w("kiosk:")
    w("  debug_port: 0               # >0 = Chromium DevTools on 127.0.0.1:<port> (development only)")
    w("")
    w("update:")
    w("  repo: \"\"                    # owner/name on GitHub; empty = the repository this was installed from")
    w("  channel: release            # release = latest GitHub release, main = newest commit of `branch`")
    w("  branch: main")
    w("  auto: false                 # true = install new versions by itself every night (04:30)")
    w("  check_hours: 6              # how often the menu checks; new versions are shown in the top bar")
    return "\n".join(L) + "\n"


async def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write", metavar="PATH")
    ap.add_argument("--city")
    ap.add_argument("--lang", default=None, choices=["uk", "en"])
    ap.add_argument("--json", action="store_true", help="print what was detected and exit")
    a = ap.parse_args()
    seats, monitors, caddy_ct = await detect_seats(), await detect_monitors(), await detect_caddy()
    if a.json:
        print(json.dumps({"seats": seats, "monitors": monitors, "caddy_ct": caddy_ct}, indent=1, default=str))
        return
    city = a.city or guess_city()
    lang = a.lang or ("uk" if city in ("Kyiv", "Kiev", "Uzhgorod", "Zaporozhye", "Simferopol") else "en")
    text = render(seats, monitors, caddy_ct, city, lang)
    if not a.write:
        sys.stdout.write(text)
        return
    if os.path.exists(a.write):
        sys.exit(f"{a.write} already exists, not overwriting")
    os.makedirs(os.path.dirname(a.write), exist_ok=True)
    with open(a.write, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {a.write}: seats {len(seats)}, DDC monitors {sum(1 for m in monitors if m['inputs'])}, "
          f"Caddy {'CT ' + str(caddy_ct) if caddy_ct else 'not found'}")


if __name__ == "__main__":
    asyncio.run(main())
